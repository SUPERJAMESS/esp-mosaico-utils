#!/usr/bin/env python3
"""Regenerate the fixed bilingual system catalog and OFL font subset.

Requires fonttools. --font accepts NotoSansCJK-Regular.ttc (SC face index 2).
Only fixed system text is embedded; Idea text uses downloaded MIFF glyphs.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path)
    parser.add_argument("--face", type=int, default=2)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    translations = json.loads((ROOT / "ui/translations.json").read_text())
    scene = json.loads((ROOT / "ui/main.json").read_text())
    out = ["// Generated by tools/prepare_system_locale.py; edit ui/translations.json.",
           "static const struct { const char *en, *zh; } translations[] = {"]
    for en, zh in translations.items():
        out.append("    {" + json.dumps(en, ensure_ascii=False) + ", " + json.dumps(zh, ensure_ascii=False) + "},")
    out.extend(["};", "static const struct { uint16_t bind; const char *text; } static_labels[] = {"])
    for obj in scene["objects"]:
        if (obj.get("bind", "").startswith("i18n_") or obj.get("bind") == "idea_heading"):
            out.append("    {GSP_VIBE_BIND_" + obj["bind"].upper() + ", " + json.dumps(obj["text"], ensure_ascii=False) + "},")
    out.append("};")
    output = "\n".join(out) + "\n"
    destination = ROOT / "components/app_ui/private/vibe_translations.inc"
    if args.check:
        assert destination.read_text() == output, "Regenerate vibe_translations.inc"
    else:
        destination.write_text(output)
    characters = set("中文English")
    for obj in scene["objects"]:
        if obj.get("font") == "fonts/MosaicoUI.otf":
            characters.update(obj.get("font_charset", "")); characters.update(obj.get("text", ""))
    from fontTools import subset
    from fontTools.ttLib import TTFont
    target = ROOT / "ui/fonts/MosaicoUI.otf"
    if args.font and not args.check:
        font = TTFont(args.font, fontNumber=args.face)
        options = subset.Options(); options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
        selection = subset.Subsetter(options=options)
        selection.populate(text="".join(characters)); selection.subset(font)
        for record in font["name"].names:
            names = {1: "Mosaico UI Subset", 2: "Regular", 3: "MosaicoUISubset-Regular", 4: "Mosaico UI Subset Regular", 6: "MosaicoUISubset-Regular"}
            if record.nameID in names: record.string = names[record.nameID].encode(record.getEncoding())
        if 'CFF ' in font:
            cff = font['CFF '].cff
            cff.fontNames = ['MosaicoUISubset-Regular']
            cff.topDictIndex[0].FamilyName = 'Mosaico UI Subset'
            cff.topDictIndex[0].FullName = 'Mosaico UI Subset Regular'
        font.save(target)
    font = TTFont(target)
    missing = {ord(c) for c in characters if not c.isspace()} - set(font.getBestCmap())
    assert not missing, "System font misses: " + str(sorted(missing))
    print("System catalog and font cover", len(characters), "characters")


if __name__ == "__main__":
    main()
